    """Initializes and returns an authenticated gspread client."""
    credentials = credentials_from_dict(_credentials_dict)
    if not credentials or not credentials.valid:
        st.warning("Invalid or missing Google credentials for gspread.")
        return None
    try:
        gc = gspread.authorize(credentials)
        return gc
    except Exception as e:
        st.error(f"Failed to initialize gspread client: {e}")
        return None

