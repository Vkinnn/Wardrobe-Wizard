def process_uploaded_files(uploaded_files):
    """Processes files uploaded via Streamlit."""
    inventory_data = []
    if not uploaded_files: return pd.DataFrame()

    for uploaded_file in uploaded_files:
        st.write(f"Processing {uploaded_file.name}...")
        image_bytes = uploaded_file.getvalue()
        image_base64 = encode_image(image_bytes)
        if not image_base64: continue

        # Use caching based on bytes hash
        img_hash = hash(image_bytes) # Simple hash for cache key
        image_description = get_description_json_cached(img_hash, image_base64)

        if image_description is None: continue # Skip non-clothing
        if "error" in image_description:
            st.warning(f"Could not get description for {uploaded_file.name}: {image_description['error']}")
            continue

        item_data = {
            "file name": uploaded_file.name, # Use uploaded file name
            "description": image_description, # Store as dict directly now
            "category": image_description.get('type', 'N/A'),
            "sub-category": image_description.get('subtype', 'N/A'),
            "color": image_description.get('color', []), # Store as list
            "pattern": image_description.get('pattern', ''),
            "weather": image_description.get('weather', []), # Store as list
            "occasion": image_description.get('occasion', []) # Store as list
        }
        inventory_data.append(item_data)

    return pd.DataFrame(inventory_data)


