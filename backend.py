class WeatherAgent:
    BASE_URL = "https://api.openweathermap.org/data/2.5/weather"
    def __init__(self, zip_code, api_key):
        if not api_key: raise ValueError("OpenWeatherMap API key required.")
        self.zip_code = zip_code
        self.api_key = api_key

    # Cache weather data for a short time
    @st.cache_data(ttl=900) # Cache for 15 minutes
    def get_weather(_self): # Use _self because st.cache_data doesn't handle instance methods well directly
        """Fetches current weather."""
        params = {'zip': f"{_self.zip_code},us", 'appid': _self.api_key, 'units': 'metric'}
        try:
            response = requests.get(_self.BASE_URL, params=params, timeout=10)
            response.raise_for_status()
            data = response.json()
            # Validation... (same as before)
            temp_celsius = data['main']['temp']
            condition = data['weather'][0]['main'].lower()
            description = data['weather'][0]['description'].lower()
            temp_fahrenheit = (temp_celsius * 9/5) + 32
            return {'temp_celsius': round(temp_celsius, 1), 'temp_fahrenheit': round(temp_fahrenheit, 1), 'condition': condition, 'description': description}
        except Exception as e:
            st.error(f"Weather fetch error: {e}")
            # Return default or raise? Returning default for smoother UI
            return {'temp_celsius': 20, 'temp_fahrenheit': 68, 'condition': 'clear', 'description': 'unknown (fetch error)'}


