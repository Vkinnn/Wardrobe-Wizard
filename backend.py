@st.cache_data(ttl=300) # Cache file list for 5 mins
def get_files_in_drive_folder(_drive_service, folder_id, after_timestamp=None):
    """Lists files in Drive folder."""
    if not _drive_service: return []
    file_details = []
    try:
        query = f"'{folder_id}' in parents and trashed=false"
        if after_timestamp: query += f" and createdTime > '{after_timestamp}'"
        page_token = None
        while True:
            results = _drive_service.files().list(
                q=query, pageSize=100, fields="nextPageToken, files(id, name, createdTime, mimeType, webViewLink, thumbnailLink)", # Get more fields
                pageToken=page_token
            ).execute()
            files = results.get("files", [])
            for file in files:
                 # Filter out non-image files if necessary based on mimeType
                 if file.get('mimeType', '').startswith('image/'):
                      file_details.append({
                           'id': file['id'],
                           'name': file['name'],
                           'createdTime': file.get('createdTime'),
                           'webViewLink': file.get('webViewLink'), # Link to view in Drive
                           'thumbnailLink': file.get('thumbnailLink') # Small preview link
                      })
            page_token = results.get('nextPageToken', None)
            if page_token is None: break
        return file_details
    except Exception as e:
        st.error(f"Error listing files in Drive folder '{folder_id}': {e}")
        return []

