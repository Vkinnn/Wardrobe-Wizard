@st.cache_data(ttl=600) # Cache for 10 minutes
def check_gsheet_id(_drive_service, folder_id, sheet_name):
    """Finds the Google Sheet ID."""
    if not _drive_service: return None, False
    try:
        query = f"'{folder_id}' in parents and mimeType='application/vnd.google-apps.spreadsheet' and name='{sheet_name}' and trashed=false"
        results = _drive_service.files().list(q=query, fields="files(id, name)").execute()
        files = results.get("files", [])
        if files:
            return files[0]["id"], True
        return None, False
    except Exception as e:
        st.error(f"Error checking GSheet ID for '{sheet_name}': {e}")
        return None, False

